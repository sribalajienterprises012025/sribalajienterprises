/**
 * Regenerates supabase/storage-policies.sql from the storage migration.
 *
 * The policies exist in two places for one reason: a hosted Supabase project
 * may not let the migrating role create them, in which case they have to be
 * run once by hand as a role that owns storage.objects. Two copies that can
 * drift is how a security rule quietly becomes wrong, so the standalone file
 * is extracted from the migration rather than maintained beside it, and CI
 * fails if the checked-in copy is stale.
 *
 *   node scripts/storage-policies.mjs           # write the file
 *   node scripts/storage-policies.mjs --check   # fail if it is out of date
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const sources = [
  'supabase/migrations/20250101000200_storage.sql',
  // The driver migration rewrites two of the four, because a business with a
  // driver in it can no longer let every member read every file.
  'supabase/migrations/20250101001000_driver_logins.sql',
].map((file) => path.join(root, file))
const target = path.join(root, 'supabase/storage-policies.sql')

const bodies = []
for (const file of sources) {
  const migration = await readFile(file, 'utf8')
  for (const match of migration.matchAll(/execute \$p\$\n([\s\S]*?)\n {2}\$p\$;/g)) {
    bodies.push(match[1].replaceAll('\n    ', '\n').trim())
  }
}

// Four from the storage migration, two rewritten by the driver one. Replayed
// in migration order, so the last definition of a policy wins — exactly what
// the database ends up with.
if (bodies.length !== 6) {
  throw new Error(`expected 6 policy statements across the migrations, found ${bodies.length}`)
}

const contents = `-- Storage access policies for the documents bucket.
--
-- Generated by scripts/storage-policies.mjs from the storage migration and the
-- driver one, replayed in that order. Edit the migrations, not this file.
--
-- Needed only when \`supabase db push\` warned that it could not apply them,
-- which happens when the role running migrations does not own storage.objects.
-- Paste this into the Supabase SQL Editor and run it once. Run it again after
-- the driver update: until you do, a driver cannot attach a delivery photo and
-- every member of the business can still read every file in the bucket.

${bodies.join('\n\n')}
`

if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8').catch(() => '')
  if (existing !== contents) {
    console.error(
      'supabase/storage-policies.sql is out of date with the storage migration.',
    )
    console.error('Run: node scripts/storage-policies.mjs')
    process.exit(1)
  }
  console.log('storage-policies.sql matches the migration')
} else {
  await writeFile(target, contents, 'utf8')
  console.log(`wrote ${path.relative(process.cwd(), target)}`)
}
