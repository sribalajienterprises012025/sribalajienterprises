/**
 * A plausible month of trading for the demo build.
 *
 * Written as base-table rows only. Every ledger, report and dashboard figure is
 * derived from these by src/demo/views.ts, exactly as Postgres derives them in
 * the real app — so what the demo shows is arithmetically true rather than a
 * set of pleasant-looking numbers typed in by hand.
 */

const DAY = 86_400_000

/** Dates are relative to today, so the demo never looks stale. */
function daysAgo(n: number): string {
  return new Date(Date.now() - n * DAY).toISOString().slice(0, 10)
}
function daysAhead(n: number): string {
  return new Date(Date.now() + n * DAY).toISOString().slice(0, 10)
}
function monthStart(offset: number): string {
  const d = new Date()
  d.setDate(1)
  d.setMonth(d.getMonth() - offset)
  return d.toISOString().slice(0, 10)
}

